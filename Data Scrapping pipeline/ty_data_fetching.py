"""# clean filter"""

# Detect English

def is_english(text):
    try:
        return detect(text) == "en"
    except:
        return False

# clean description

def clean_text_pipeline(title,description):
    text = title + " " + (description or "")

    text = re.sub(r'http\S+', '', text) # remove link
    text = re.sub(r'\d{1,2}:\d{2}', '', text) # remove timestamp
    text = re.sub(r'\s+', ' ', text) # remove white space

    return text.strip()

# extract hashtag

def extract_hashtag(text):
    hashtags = re.findall(r"#\w+", text)
    return hashtags

# Duration parser

def parse_duration(d):
    try:
        return int(isodate.parse_duration(d).total_seconds())
    except:
        return None

# Emoji count

def count_emoji(text):
    return sum(1 for c in text if c in emoji.EMOJI_DATA)

"""# video search"""

def search_video(query):
    if query in search_cache:
        return search_cache[query]

    try:
        req = youtube.search().list(
            part="id,snippet",
            q=query,
            type="video",
            maxResults=20,
            regionCode="IN",
            relevanceLanguage="en"
        )
        res = req.execute()
        ids = [v["id"]["videoId"] for v in res.get("items", [])]
        ids = list(set(ids))
        search_cache[query] = ids
        print(f"Query '{query}' → {len(ids)}")
        return ids

    except HttpError as e:
        print("Quota or API error:", e)
        return []

"""# video details"""

def get_video_details(video_ids, niche):
    rows = []

    for i in range(0, len(video_ids), VIDEO_BATCH):
        batch = video_ids[i:i+VIDEO_BATCH]

        new_batch = [v for v in batch if v not in video_cache]

        if new_batch:
            req = youtube.videos().list(
                part="snippet,statistics,contentDetails",
                id=",".join(new_batch)
            )
            res = req.execute()

            for v in res.get("items", []):
                video_cache[v["id"]] = v

        # PROCESS FROM CACHE
        for vid in batch:
            v = video_cache.get(vid)
            if not v:
                continue

            sn = v["snippet"]
            st = v.get("statistics",{})
            cd = v.get("contentDetails",{})

             # Duration Filter

            duration = parse_duration(cd.get("duration"))
            if duration is None:
                continue
            if duration > MAX_DURATION or duration < 5:
                continue

            content_type = "short" if duration <= SHORT_LIMIT else "video"

            # Caption

            title = sn.get("title","")
            description = sn.get("description","")
            full_text_raw = title + " " + description

            # Apply filter

            if not full_text_raw or len(full_text_raw.strip()) < 30:
                continue

            if not is_english(full_text_raw):
                continue

            # Hashtag
            hashtags = extract_hashtag(full_text_raw)
            hashtag_count = len(hashtags)

            # Engagement
            views = int(st.get("viewCount",0))
            likes = int(st.get("likeCount",0))
            comments = int(st.get("commentCount",0))

            if views < 1000 or likes < 10:
                continue

            # clen text
            full_text_clean = clean_text_pipeline(title,description)

            rows.append({
                "post_id": v["id"],
                "channel_id": sn["channelId"],

                # Raw text
                "caption_raw": full_text_raw,

                #clean text
                "full_text_clean": full_text_clean,

                "hashtags": " ".join(hashtags),
                "hashtag_count": hashtag_count,
                "emoji_count": count_emoji(full_text_raw),

                "likes": likes,
                "views": views,
                "comments": comments,

                "duration_sec": duration,
                "content_type": content_type,
                "category_id": sn.get("categoryId"),
                "timestamp": sn["publishedAt"],
            })

    print(f"[DEBUG] Rows after filtering: {len(rows)}")

    return rows

"""# Channel expansion"""

def get_uploads(channel_id):
    if channel_id in channel_cache:
        return channel_cache[channel_id]

    try:
        req = youtube.channels().list(
            part="contentDetails",
            id=channel_id
        )
        res = req.execute()

        if not res.get("items"):
            return None

        playlist = res["items"][0]["contentDetails"]["relatedPlaylists"]["uploads"]
        channel_cache[channel_id] = playlist
        return playlist

    except Exception as e:
        return None

def expand_channel(channel_id):
    vids = []

    if channel_id in channel_cache:
        return vids

    playlist = get_uploads(channel_id)

    if not playlist:
        return vids

    next_page = None

    try:
        while len(vids) < VIDEOS_PER_CHANNEL:
            req = youtube.playlistItems().list(
                part="contentDetails",
                playlistId=playlist,
                maxResults=50,
                pageToken=next_page
            )
            res = req.execute()

            for v in res.get("items", []):
                vid = v["contentDetails"]["videoId"]
                vids.append(vid)

                if len(vids) >= VIDEOS_PER_CHANNEL:
                    break

            next_page = res.get("nextPageToken")

            if not next_page:
                break

    except:
        pass

    return list(set(vids))

"""# channel stats"""

def fetch_channel_stats(channel_ids):
    stats = {}

    for i in range(0, len(channel_ids), 50):
        batch = channel_ids[i:i+50]

        req = youtube.channels().list(
            part="statistics",
            id=",".join(batch)
        )
        res = req.execute()

        for c in res.get("items", []):
            stats[c["id"]] = {
                "followers_count": int(c["statistics"].get("subscriberCount", 0) or 0),
                "total_posts": int(c["statistics"].get("videoCount", 0))
            }

    return stats

