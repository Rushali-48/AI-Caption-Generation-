def build_dataset():
    all_video_ids = set()
    channel_ids = set()
    channel_niche_map = {}

    print("\n STEP 1: SEED SEARCH ")
    seed_query_results = {}

    for niche, queries in SEED_QUERIES.items():
        for q in queries:
            vids = search_video(q)
            seed_query_results[q] = vids
            all_video_ids.update(vids)

    print(f"Seed videos: {len(all_video_ids)}")

    print("\n STEP 2: GET CHANNELS ")
    seed_data = []

    # fetch seed data per niche
    for niche, queries in SEED_QUERIES.items():
        niche_video_ids = []

        for q in queries:
            vids = seed_query_results[q]
            niche_video_ids.extend(vids)

        data = get_video_details(niche_video_ids, niche)
        if not data:
            continue

        seed_data.extend(data)

        # map channel  niche
        for d in data:
            channel_ids.add(d["channel_id"])

            if d["channel_id"] not in channel_niche_map:
                channel_niche_map[d["channel_id"]] = niche

    print(f"Channels found: {len(channel_ids)}")

    print("\n STEP 3: EXPAND CHANNELS ")
    expanded_ids = set()

    for i, ch in enumerate(list(channel_ids)[:MAX_CHANNELS]):
        vids = expand_channel(ch)
        expanded_ids.update(vids)

        if len(expanded_ids) >= TARGET_VIDEOS * 1.5:
            break

        if i % 50 == 0:
            print(f"Expanded from {i} channels {len(expanded_ids)} videos")

    print(f"Total expanded videos: {len(expanded_ids)}")

    print("\n STEP 4: FINAL VIDEO DETAILS ")

    # BATCH FETCH
    expanded_ids = list(expanded_ids)
    all_video_data = get_video_details(expanded_ids, "temp")

    final_data = []

    for d in all_video_data:
        ch = d["channel_id"]
        niche = channel_niche_map.get(ch, "general")
        d["niche"] = niche
        final_data.append(d)

    df = pd.DataFrame(final_data).drop_duplicates("post_id")
    df = df[df["caption_raw"].str.len() > 30]
    df = df[df["views"] > 1000]
    df = df[df["likes"] > 10]

    df = df.sample(n=min(TARGET_VIDEOS, len(df)), random_state=42)

    print("\nSTEP 5: CHANNEL STATS ")
    ch_stats = fetch_channel_stats(df["channel_id"].unique())

    df["followers_count"] = df["channel_id"].map(lambda x: ch_stats.get(x, {}).get("followers_count", 0))
    df["total_posts"] = df["channel_id"].map(lambda x: ch_stats.get(x, {}).get("total_posts", 0))


    print("\n FINAL DEBUG ")
    print("Rows:", len(df))
    print("Unique channels:", df["channel_id"].nunique())
    print("Short vs Video:\n", df["content_type"].value_counts())
    print("\nNiche Distribution:\n", df["niche"].value_counts())

    df.to_csv("dataset_5k.csv", index=False)
    print("Dataset saved!")

    return df

# RUN
build_dataset()

